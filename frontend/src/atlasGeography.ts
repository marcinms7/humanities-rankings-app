function normalise(value: string) {
  return value
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[\s.'’()-]/g, '')
}

const coordinates = new Map<string, readonly [number, number]>()
for (const [names, longitude, latitude] of locations) {
  for (const name of names) {
    const key = normalise(name)
    if (!coordinates.has(key)) coordinates.set(key, [longitude, latitude])
  }
}
for (const [alias, canonical] of Object.entries(aliases)) {
  const point = coordinates.get(normalise(canonical))
  if (point) coordinates.set(normalise(alias), point)
}

/** Match whole saved labels only. No substring inference for mixed or historical contexts. */
export function countryCoordinates(key: string): readonly [number, number] | undefined {
  return coordinates.get(normalise(key))
}

export function isMappedCountry(key: string): boolean {
  return countryCoordinates(key) !== undefined
}

/** Equirectangular projection; identical to the checked-in Natural Earth paths. */
export function projectCountry(key: string): readonly [number, number] | undefined {
  const coordinate = countryCoordinates(key)
  return coordinate ? [(coordinate[0] + 180) * 2, (90 - coordinate[1]) * 2] : undefined
}
